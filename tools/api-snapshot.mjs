import { spawnSync } from 'node:child_process';
import { readFile, writeFile, mkdir, rm, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
process.chdir(root);
const declarations = 'packages/kit/dist/types';
await rm(declarations, { recursive: true, force: true });
const build = spawnSync('pnpm', ['build:kit', '--force'], { stdio: 'inherit' });
if (build.status !== 0) process.exit(build.status ?? 1);
const graph = new Map();
const unresolved = new Set();
const pending = ['index.d.ts'];
while (pending.length) {
  const name = pending.pop();
  if (graph.has(name)) continue;
  const source = (await readFile(path.join(declarations, name), 'utf8')).replace(/\r\n/g, '\n').trim();
  graph.set(name, source);
  for (const ref of ts.preProcessFile(source).importedFiles) {
    if (!ref.fileName.startsWith('.')) continue;
    const base = path.posix.join(path.posix.dirname(name), ref.fileName);
    let resolved;
    for (const candidate of [base + '.d.ts', base + '/index.d.ts', base.replace(/\.js$/, '.d.ts')]) {
      try { await access(path.join(declarations, candidate)); resolved = candidate; break; } catch {}
    }
    if (!resolved) { unresolved.add(`${name} -> ${ref.fileName}`); continue; }
    pending.push(resolved);
  }
}
const report = '# Kit declaration graph\n\nGenerated by `pnpm api:update`. Includes relative imports reachable from the public entry.\n\n' +
  ([...unresolved].sort().map(ref => `Missing emitted declaration: ${ref}\n`).join('') + '\n') + [...graph].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)
    .map(([name, source]) => `## ${name}\n\n\`\`\`ts\n${source}\n\`\`\`\n`).join('\n');
const target = 'packages/kit/api/kit.api.md';
if (process.argv.includes('--update')) {
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, report);
} else if (await readFile(target, 'utf8') !== report) {
  console.error('Public API differs. Review the change, then run pnpm api:update.');
  process.exitCode = 1;
} else {
  console.log('Public API matches the committed report.');
}
