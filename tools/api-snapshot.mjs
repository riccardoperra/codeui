import { spawnSync } from "node:child_process";
import { readFile, writeFile, mkdir, rm, access } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
process.chdir(root);
const declarations = "packages/kit/dist/types";
if (!process.argv.includes("--no-build")) {
	await rm(declarations, { recursive: true, force: true });
	const build = spawnSync("pnpm", ["build:kit", "--force"], { stdio: "inherit" });
	if (build.status !== 0) process.exit(build.status ?? 1);
}
const graph = new Map();
const unresolved = new Set();
const manifest = JSON.parse(await readFile("packages/kit/package.json", "utf8"));
const styles = JSON.parse(await readFile("packages/styles/package.json", "utf8"));
const typesTarget = entry =>
	typeof entry === "string" ? undefined : (entry?.types ?? entry?.import?.types);
const styleDeclaration = target =>
	"@codeui/styles/" + path.posix.relative("dist/types", target);
const declarationPath = name =>
	name.startsWith("@codeui/styles/")
		? path.join("packages/styles/dist/types", name.slice("@codeui/styles/".length))
		: path.join(declarations, name);
const subpaths = Object.values(manifest.typesVersions?.["*"] ?? {})
	.flat()
	.map(file => path.posix.relative("dist/types", file));
const pending = ["index.d.ts", ...subpaths];
for (const entry of Object.values(styles.exports)) {
	const target = typesTarget(entry);
	if (target) pending.push(styleDeclaration(target));
}
while (pending.length) {
	const name = pending.pop();
	if (graph.has(name)) continue;
	const source = (await readFile(declarationPath(name), "utf8"))
		.replace(/\r\n/g, "\n")
		.trim();
	graph.set(name, source);
	// ts.preProcessFile skips `export * as ns from`, so read every specifier.
	for (const [, specifier] of source.matchAll(
		/(?:\bfrom\s*|\bimport\s*\(\s*)["'](\.[^"']+|@codeui\/styles(?:\/[^"']+)?)["']/g,
	)) {
		if (specifier.startsWith("@codeui/styles")) {
			const subpath = specifier.slice("@codeui/styles".length);
			const target = typesTarget(styles.exports[subpath ? "." + subpath : "."]);
			if (target) pending.push(styleDeclaration(target));
			else unresolved.add(`${name} -> ${specifier}`);
			continue;
		}
		const base = path.posix.join(path.posix.dirname(name), specifier);
		let resolved;
		for (const candidate of [
			base + ".d.ts",
			base + "/index.d.ts",
			base.replace(/\.js$/, ".d.ts"),
		]) {
			try {
				await access(declarationPath(candidate));
				resolved = candidate;
				break;
			} catch {}
		}
		if (!resolved) {
			unresolved.add(`${name} -> ${specifier}`);
			continue;
		}
		pending.push(resolved);
	}
}
if (unresolved.size)
	throw new Error(`Unresolved public declarations:\n${[...unresolved].join("\n")}`);
const report =
	"# Kit and styles declaration graphs\n\nGenerated by `pnpm api:update`. Includes reachable style declarations across the package boundary.\n\n" +
	([...unresolved]
		.sort()
		.map(ref => `Missing emitted declaration: ${ref}\n`)
		.join("") +
		"\n") +
	[...graph]
		.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
		.map(([name, source]) => `## ${name}\n\n\`\`\`ts\n${source}\n\`\`\`\n`)
		.join("\n");
const target = "packages/kit/api/kit.api.md";
if (process.argv.includes("--update")) {
	await mkdir(path.dirname(target), { recursive: true });
	await writeFile(target, report);
} else if ((await readFile(target, "utf8")) !== report) {
	console.error("Public API differs. Review the change, then run pnpm api:update.");
	process.exitCode = 1;
} else {
	console.log("Public API matches the committed report.");
}
